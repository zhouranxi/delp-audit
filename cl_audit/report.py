"""Human-readable rendering of a six-gate report."""
import json


def _cell(s):
    return str(s).replace("|", "\\|").replace("\n", " ")


def render_markdown(report):
    s = report["summary"]
    L = [
        "# cl-audit — %s" % report["name"],
        "",
        "Records: **%d**  |  PASS %d / WARN %d / FAIL %d / SKIP %d"
        % (report["n_records"], s["PASS"], s["WARN"], s["FAIL"], s["SKIP"]),
        "",
        "A FAIL blocks the claim. A WARN requires an explicit caveat in any report. "
        "A SKIP is missing evidence, not a pass.",
        "",
        "| Gate | Status | Finding |",
        "|---|---|---|",
    ]
    for r in report["results"]:
        L.append("| %s %s | **%s** | %s |"
                 % (r["gate"], _cell(r["title"]), r["status"], _cell(r["detail"])))
    if report["notes"]:
        L += ["", "## Input notes", ""]
        L += ["- " + _cell(n) for n in report["notes"]]
    L += ["", "## Evidence", ""]
    for r in report["results"]:
        if r["evidence"]:
            L.append("- **%s**: `%s`" % (r["gate"],
                     json.dumps(r["evidence"], ensure_ascii=False, sort_keys=True)))
    L += ["", "---", "",
          "Generated by `cl-audit check`. This tool audits measurement validity; "
          "it does not validate the scientific design or the correctness of the "
          "training code.", ""]
    return "\n".join(L)
